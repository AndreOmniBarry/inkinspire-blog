"""
Builds Inkinspire's self-hosted variable fonts (all SIL Open Font Licence, from github.com/google/fonts).

Why a build step: we want ONE small, preloadable file per family/style that still covers English,
Nigerian Pidgin, Yoruba, Igbo and Hausa (dot-below vowels, tone marks, hooked letters) and the naira sign,
while keeping the weight and optical-size axes that make the typography sing.

Usage:  pip install fonttools brotli
        python3 scripts/build-fonts.py <dir-with-source-ttfs>
Outputs are committed to src/fonts/, so this only re-runs when upgrading fonts.
"""
import io, sys, pathlib
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

SRC = pathlib.Path(sys.argv[1])
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "public" / "fonts"
OUT.mkdir(parents=True, exist_ok=True)

RANGES = [
    (0x20, 0x7E), (0xA0, 0xFF), (0x100, 0x17F),            # Latin, Latin-1, Latin Extended-A
    (0x181, 0x181), (0x186, 0x186), (0x18A, 0x18A), (0x18E, 0x18E), (0x190, 0x190),
    (0x198, 0x199), (0x1B3, 0x1B4), (0x1CD, 0x1DC), (0x1F8, 0x1F9),  # Hausa hooks, tone-marked vowels, ǹ
    (0x253, 0x254), (0x256, 0x257), (0x25B, 0x25B),
    (0x2BC, 0x2BC), (0x2C6, 0x2C6), (0x2DA, 0x2DA), (0x2DC, 0x2DC),
    (0x300, 0x304), (0x306, 0x306), (0x308, 0x308), (0x30C, 0x30C), (0x323, 0x323), (0x329, 0x329),
    (0x1E62, 0x1E63), (0x1EB8, 0x1EBD), (0x1ECA, 0x1ECD), (0x1EE4, 0x1EE5),  # Ṣ Ẹ Ẽ Ị Ọ Ụ
    (0x2002, 0x200A), (0x2010, 0x2014), (0x2018, 0x201E), (0x2020, 0x2022), (0x2026, 0x2026),
    (0x2030, 0x2030), (0x2032, 0x2033), (0x2039, 0x203A), (0x2044, 0x2044),
    (0x20A6, 0x20A6), (0x20AC, 0x20AC), (0x2122, 0x2122), (0x2190, 0x2193), (0x2212, 0x2212),
    (0x2E3A, 0x2E3B), (0x2042, 0x2042), (0x2766, 0x2767), (0x2042, 0x2042),
]
UNICODES = sorted({c for a, b in RANGES for c in range(a, b + 1)})

# (family, css name, style, fallback local font, fallback xAvgCharWidth/unitsPerEm)
# Same method as next/font: average advance of a frequency-weighted a–z sample vs the fallback's.
SAMPLE = "aaabcdeeeefghiijklmnnoopqrrssttuvwxyz      "
FALLBACKS = {"serif": ("Times New Roman", 854.3953488372093 / 2048), "sans": ("Arial", 934.5116279069767 / 2048)}


def avg_width(font):
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    widths = [hmtx[cmap[ord(c)]][0] for c in SAMPLE if ord(c) in cmap]
    return sum(widths) / len(widths)

JOBS = [
    ("Fraunces.ttf", "fraunces-normal.woff2", {"SOFT": 0, "WONK": 0, "wght": (300, 640)}),
    ("Fraunces-Italic.ttf", "fraunces-italic.woff2", {"SOFT": 0, "WONK": 0, "wght": (300, 640)}),
    ("Newsreader.ttf", "newsreader-normal.woff2", {"wght": (400, 600), "opsz": 16}),
    ("Newsreader-Italic.ttf", "newsreader-italic.woff2", {"wght": (400, 600), "opsz": 16}),
    ("InstrumentSans.ttf", "instrument-sans-normal.woff2", {"wdth": 100, "wght": (400, 700)}),
]

FAMILY = {
    "fraunces": ("Fraunces", "serif", "300 640"),
    "newsreader": ("Newsreader", "serif", "400 600"),
    "instrument-sans": ("Instrument Sans", "sans", "400 700"),
}
css = ["/* GENERATED by scripts/build-fonts.py. Self-hosted variable fonts (SIL OFL) + metric-matched fallbacks. */"]
fallback_done = set()

for src, dst, axes in JOBS:
    font = TTFont(SRC / src)
    key = dst.rsplit("-", 1)[0]
    style = "italic" if "italic" in dst else "normal"
    fam, kind, weight = FAMILY[key]
    upm = font["head"].unitsPerEm
    hhea = font["hhea"]
    os2 = font["OS/2"]
    avg = avg_width(font) / upm
    local_name, fb_avg = FALLBACKS[kind]
    size_adjust = avg / fb_avg
    css.append(f"""@font-face {{
  font-family: "{fam}";
  src: url("/fonts/{dst}") format("woff2");
  font-style: {style};
  font-weight: {weight};
  font-display: swap;
}}""")
    if key not in fallback_done:
        fallback_done.add(key)
        css.append(f"""@font-face {{
  font-family: "{fam} Fallback";
  src: local("{local_name}");
  ascent-override: {hhea.ascent / upm / size_adjust * 100:.2f}%;
  descent-override: {abs(hhea.descent) / upm / size_adjust * 100:.2f}%;
  line-gap-override: {hhea.lineGap / upm / size_adjust * 100:.2f}%;
  size-adjust: {size_adjust * 100:.2f}%;
}}""")  # opsz pinned to 16 for Newsreader: text cut, a third of the size
    present = {a.axisTag for a in font["fvar"].axes}
    font = instancer.instantiateVariableFont(font, {k: v for k, v in axes.items() if k in present})
    buf = io.BytesIO(); font.save(buf); buf.seek(0); font = TTFont(buf)  # reload: subsetter needs fresh tables
    opts = subset.Options()
    opts.layout_features = ["*"]
    opts.flavor = "woff2"
    opts.hinting = False
    opts.desubroutinize = True
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)
    font.flavor = "woff2"
    font.save(OUT / dst)
    print(f"{dst}: {(OUT / dst).stat().st_size // 1024} KB, axes {[a.axisTag for a in font['fvar'].axes]}")

(ROOT / "src" / "styles" / "fonts.css").write_text("\n".join(css) + "\n")
print("wrote src/styles/fonts.css")
