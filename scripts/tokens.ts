/**
 * `pnpm tokens`          → writes src/styles/tokens.css from src/styles/tokens.ts
 * `pnpm tokens --check`  → fails if tokens.css is out of date (CI)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  palettes,
  themeNames,
  typeScale,
  readingSize,
  space,
  radius,
  motion,
  categoryColours,
  type ThemeName,
} from "../src/styles/tokens";

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

function themeVars(name: ThemeName): string {
  const p = palettes[name];
  const lines: string[] = [];
  for (const [k, v] of Object.entries(p)) {
    if (k === "categories") continue;
    lines.push(`  --${kebab(k)}: ${v};`);
  }
  for (const c of categoryColours) {
    const [bg, ink] = p.categories[c];
    lines.push(`  --cat-${c}-bg: ${bg};`, `  --cat-${c}-ink: ${ink};`);
  }
  lines.push(`  color-scheme: ${name === "midnight" ? "dark" : "light"};`);
  return lines.join("\n");
}

const statics = [
  ...Object.entries(typeScale).map(([k, v]) => `  --step-${k.replace("-", "n")}: ${v};`),
  `  --reading-size: ${readingSize};`,
  ...Object.entries(space).map(([k, v]) => `  --space-${k}: ${v};`),
  ...Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v};`),
  `  --dur-fast: ${motion.fast};`,
  `  --dur-base: ${motion.base};`,
  `  --dur-slow: ${motion.slow};`,
  `  --ease: ${motion.ease};`,
  `  --ease-out: ${motion.easeOut};`,
  `  --measure: 66ch;`,
].join("\n");

const css = `/* GENERATED by \`pnpm tokens\` from src/styles/tokens.ts. Do not edit by hand. */

:root {
${statics}
}

:root,
[data-theme="paper"] {
${themeVars("paper")}
}

[data-theme="sepia"] {
${themeVars("sepia")}
}

[data-theme="midnight"] {
${themeVars("midnight")}
}

/* No-JS visitors who prefer dark get Midnight; the inline theme script sets data-theme for everyone else. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
${themeVars("midnight").replace(/^/gm, "  ")}
  }
}
`;

const out = join(process.cwd(), "src/styles/tokens.css");
if (process.argv.includes("--check")) {
  const current = readFileSync(out, "utf8");
  if (current !== css) {
    console.error("tokens.css is out of date. Run `pnpm tokens`.");
    process.exit(1);
  }
  console.log("tokens.css is up to date.");
} else {
  writeFileSync(out, css);
  console.log(`Wrote ${out} (${themeNames.length} themes).`);
}
